def division_name(code: str) -> str:
    """'24110' → '1차 금속 제조업'. 세부 업종 이름이 있으면 그것을 쓴다 ('20423' → '화장품 제조업'). 모르면 빈 문자열."""
    code = code or ""
    for n in range(len(code), 2, -1):
        if code[:n] in SUBCLASSES:
            return SUBCLASSES[code[:n]]
    return DIVISIONS.get(code[:2], "")


def label(code: str) -> str:
    """화면 표시용: 'KSIC 2411 · 1차 금속 제조업'."""
    if not code:
        return "업종코드 없음"
    name = division_name(code)
    return f"KSIC {code}" + (f" · {name}" if name else "")
